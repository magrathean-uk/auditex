"""Mutation corpus: operators over the template renders (check recall and false positives).

Every mutant type is a function (pair, ctx, rng, env) -> {"output": obj} | {"output_text": str} | None (not applicable to this pair) with
  group    the check it is designed for (S, a, b, c, d, e) or "benign" (a false-positive control: every check must pass);
  expect   the checks of which at least one must fail (a miss is a mutant that none of them flags);
  A planted token is only planted when it is NOT already in the prompt's whitelist (otherwise it would not be an error).
Mutants are generated by the same author as the checkers: the corpus measures regressions and obvious blind spots, not unknown ones (see REVIEW-ASKS-REDTEAM.md).
"""
import copy
import json
