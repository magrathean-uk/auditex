FLIPS = [(r"\bOff\b", "On"), (r"\boff\b", "on"), (r"\bOn\b", "Off"), (r"\benabled\b", "disabled"), (r"\bdisabled\b", "enabled"), (r"\bEnabled\b", "Disabled"),
         (r"\btrue\b", "false"), (r"\bfalse\b", "true"), (r"\bBlock\b", "Allow"), (r"\ballowed\b", "blocked"), (r"\bAll users\b", "No users")]


def _flip_step(o):
    for i, s in enumerate(o["remediation_steps"]):
        for rx, rep in FLIPS:
            if re.search(rx, s):
                o["remediation_steps"][i] = re.sub(rx, rep, s, count=1)
                return o
    return None


