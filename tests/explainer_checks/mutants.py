def _pp_sentence(o, min_content=9):
    """(step index, sentence index, sentences) of the first sentence with enough content tokens to be paraphrased under the rule (shorter ones must be verbatim)."""
    from .chk_e import content_tokens
    for i, s in enumerate(o["remediation_steps"]):
        ss = sentence_split(s)
        for j, x in enumerate(ss):
            if len(content_tokens(x)) >= min_content:
                return i, j, ss
    return None


def _pp_apply(o, fn):
    hit = _pp_sentence(o)
    if not hit:
        return None
    i, j, ss = hit
    if not (ss[j][0].isupper() and ss[j][-1] in ".!?"):      # a fragment of a split unit is not a sentence a model would paraphrase
        return None
    new = fn(ss[j])
    if new is None or new == ss[j]:
        return None
    ss[j] = new
    step = " ".join(ss)
    if words(step) > 30:
        return None
    o["remediation_steps"][i] = step
    return {"output": o}


