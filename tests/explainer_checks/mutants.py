REG = []
LIM_WORDS, LIM_SENT = 80, 3


def mutant(name, group, expect=(), desc=""):
    def deco(fn):
        REG.append({"name": name, "group": group, "expect": list(expect), "benign": group == "benign", "desc": desc or (fn.__doc__ or ""), "fn": fn})
        return fn
    return deco


def base(p):
    return copy.deepcopy(p["output"])


def add(o, text):
    o["explanation"] = o["explanation"].rstrip() + " " + text
    return o


def absent(ctx, *toks):
    for t in toks:
        n = norm(t)
        if n in ctx.W.text or n in ctx.W.names or n in ctx.W.numbers or n in ctx.W.counts:
            return False
    return True


def fits(o):
    return words(o["explanation"]) <= LIM_WORDS and len(sentence_split(o["explanation"])) <= LIM_SENT


